const assert=require('node:assert/strict');
const C=require('../../charts.js');
const t=(a,r,extra={})=>({appointedIso:a,resignedIso:r||'',role:'director',...extra});
const o={kind:'company',complete:true,status:'active',today:'2026-11-06'};
const terms=[t('2019-01-01','2020-02-01',{appointmentKey:'a'}),t('2021-01-01','2022-01-01',{appointmentKey:'b'}),t('2024-01-01','',{appointmentKey:'c'})];
assert.equal(C.analyse(terms,o).eligible,true);
assert.equal(C.analyse(terms.map(x=>({...x,role:'secretary'})),o).eligible,false);
assert.equal(C.analyse(terms,{...o,complete:false}).reason,'partial');
assert.equal(C.analyse(terms,{...o,available:false}).reason,'unavailable');
assert.equal(C.analyse([t('2020-10-01','',{appointmentKey:'a'}),t('2020-10-01','',{appointmentKey:'b'}),t('2020-10-01','',{appointmentKey:'c'})],o).eligible,false);
assert.equal(C.analyse([...terms,t('','',{appointedBefore:'1991-06-07',pre1992:true,appointmentKey:'d'})],o).eligible,true);
assert.equal(C.analyse([...terms,t('','',{appointedBefore:'2024-06-07',pre1992:true,appointmentKey:'d'})],o).quality,false);
assert.equal(C.analyse([...terms,t('','',{appointmentKey:'d'})],o).quality,false);
assert.equal(C.analyse([...terms,terms[0]],o).quality,false);
assert.equal(C.analyse([...terms,t('2024-02-30','',{appointmentKey:'d'})],o).quality,false);
assert.equal(C.analyse([...terms,t('2024-03-01','2023-01-01',{appointmentKey:'d'})],o).quality,false);
assert.equal(C.analyse([...terms,t('2027-03-01','',{appointmentKey:'d'})],o).quality,false);
assert.equal(C.analyse(terms,{...o,status:'dissolved'}).stockSafe,false);
assert.equal(C.analyse(terms,{...o,ceased:'2020-01-01'}).stockSafe,false);
assert.equal(C.analyse(terms.map((x,i)=>({...x,number:String(i),roleCode:'director',statusCode:i===2?'dissolved':'active'})),{...o,kind:'person'}).stockSafe,false);
assert.equal(C.analyse(terms,o).rows.at(-1).n,1);
const old=C.analyse([...terms,t('','2023-01-01',{appointedBefore:'1992-11-30',pre1992:true,appointmentKey:'old'})],o);
assert.equal(old.events.filter(e=>e.kind==='a').length,3);
assert.equal(old.rows.find(r=>r.y===2019).n,2);
console.log('18 chart invariants passed');
